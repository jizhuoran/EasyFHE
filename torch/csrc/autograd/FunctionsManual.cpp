Tensor maybe_multiply(const Tensor& t, const Scalar& s) {
  bool is_one = false;
  if (s.isFloatingPoint()) {
    is_one = s.toSymFloat() == 1;
  } else if (s.isIntegral(true)) {
    is_one = s.toSymInt() == 1;
  }

  if (is_one) {
    return t;
  } else {
    return t * s;
  }
}

int64_t _safe_size(IntArrayRef sizes, IntArrayRef dim) {
  int64_t size = 1;
  if (sizes.empty()) {
    return 1;
  }
  for (auto d : dim) {
    d = at::maybe_wrap_dim(d, static_cast<int64_t>(sizes.size()));
    size *= sizes[d];
  }
  return size;
}

static c10::SymInt _safe_size(c10::SymIntArrayRef sizes, c10::IntArrayRef dim) {
  c10::SymInt size = 1;
  if (sizes.empty()) {
    return 1;
  }
  for (auto d : dim) {
    d = at::maybe_wrap_dim(d, static_cast<int64_t>(sizes.size()));
    size *= sizes[d];
  }
  return size;
}

Tensor handle_r_to_c(ScalarType self_st, Tensor gradient_result) {
  if (!at::isComplexType(self_st) && gradient_result.is_complex()) {
    // R -> C
    return at::real(gradient_result);
  }
  return gradient_result;
}

static Tensor handle_r_to_c(const Tensor& self, Tensor gradient_result) {
  if (!self.is_complex() && gradient_result.is_complex()) {
    // R -> C
    return at::real(gradient_result);
  }
  return gradient_result;
}

Tensor restore_reduced_dims(
    const Tensor& output,
    IntArrayRef dims,
    bool keepdim) {
  if (keepdim) {
    return output;
  }
  auto total_dims = output.dim() + dims.size();
  std::vector<c10::SymInt> target_shape(total_dims, 0);
  for (int64_t i : dims) {
    if (i < 0) {
      i = static_cast<int64_t>(total_dims) + i;
    }
    target_shape[i] = 1;
  }
  int64_t j = 0;
  for (const c10::SymInt& i : output.sym_sizes()) {
    while (target_shape[j] > 0)
      j++;
    target_shape[j++] = i;
  }
  return output.reshape_symint(target_shape);
}

Tensor scale_grad_by_count(
    const Tensor& grad,
    const Tensor& mask,
    IntArrayRef dims) {
  return (grad / mask.sum(dims, true)) * mask;
}

Tensor amaxamin_jvp(
    const Tensor& x,
    const Tensor& dx,
    const Tensor& result,
    IntArrayRef dim,
    bool keepdim) {
  auto mask = x == restore_reduced_dims(result, dim, keepdim);
  return at::where(mask, dx, 0.).sum(dim, keepdim) / mask.sum(dim, keepdim);
}

// Builds the dims vector for aminmax: all dims when dim is nullopt,
// or the single wrapped dim otherwise.
static std::vector<int64_t> _aminmax_dims(
    const Tensor& self,
    std::optional<int64_t> dim_opt) {
  if (dim_opt.has_value()) {
    return {at::maybe_wrap_dim(*dim_opt, self.dim())};
  }
  std::vector<int64_t> dims(self.dim());
  std::iota(dims.begin(), dims.end(), 0);
  return dims;
}

Tensor aminmax_backward(
    const Tensor& self,
    std::optional<int64_t> dim,
    bool keepdim,
    const Tensor& grad_min,
    const Tensor& grad_max,
    const Tensor& min,
    const Tensor& max) {
  auto dims_vec = _aminmax_dims(self, dim);
  IntArrayRef dims(dims_vec);
  Tensor result;

  if (grad_min.defined()) {
    auto grad_min_expanded = restore_reduced_dims(grad_min, dims, keepdim);
    auto min_mask = (self == restore_reduced_dims(min, dims, keepdim));
    result = scale_grad_by_count(grad_min_expanded, min_mask, dims);
  }

  if (grad_max.defined()) {
    auto grad_max_expanded = restore_reduced_dims(grad_max, dims, keepdim);
    auto max_mask = (self == restore_reduced_dims(max, dims, keepdim));
    auto grad_max_result =
        scale_grad_by_count(grad_max_expanded, max_mask, dims);

    if (result.defined()) {
      if (!areAnyTensorSubclassLike({result, grad_max_result})) {
        result.add_(grad_max_result);
      } else {
        result = result + grad_max_result;
      }
    } else {
      result = grad_max_result;
    }
  }

  return result;
}

Tensor aminmax_jvp(
    const Tensor& self_p,
    const Tensor& self_t,
    const Tensor& result,
    std::optional<int64_t> dim,
    bool keepdim) {
  auto dims_vec = _aminmax_dims(self_p, dim);
  return amaxamin_jvp(self_p, self_t, result, IntArrayRef(dims_vec), keepdim);
}

